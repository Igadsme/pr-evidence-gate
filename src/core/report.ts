import type { Evidence } from "./schema.js";

export function renderEvidenceCard(evidence: Evidence): string {
  const rows = evidence.checks.map((check) => `| ${check.kind} | ${check.status} | ${escape(check.summary)} |`).join("\n");
  const limitations = evidence.limitations.length === 0 ? "None recorded." : evidence.limitations.map((value) => `- ${escape(value)}`).join("\n");
  return [
    "<!-- pr-evidence-gate -->", "## PR Evidence Gate", "",
    "> This report verifies selected evidence. It is not a certification of complete code correctness.", "",
    `- Repository: \`${evidence.repository}\``, `- Base: \`${evidence.baseSha}\``, `- Head: \`${evidence.headSha}\``, "",
    "| Check | Status | Summary |", "| --- | --- | --- |", rows || "| — | SKIPPED | No checks were executed. |", "",
    "### Limitations", limitations, "", `Generated by PR Evidence Gate ${evidence.verifier.version}.`,
  ].join("\n");
}

function escape(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}
